function generateRealKlines(): ChanK[] {
  return REAL_K_ROWS.map(([time, open, high, low, close], index) => ({
    id: index + 1,
    symbol: '000001',
    time: new Date(time),
    open,
    high,
    low,
    close,
    volume: '10000',
    amount: '1000000',
  }));
}

function generateSampleKlines(count = 50): ChanK[] {
  const klines: ChanK[] = [];
  let price = 100;
  for (let i = 0; i < count; i++) {
    const isUp = i % 8 < 4;
    const delta = isUp ? 2.5 : -2.0;
    const open = price;
    const close = price + delta;
    const high = Math.max(open, close) + 1.0;
    const low = Math.min(open, close) - 1.0;
    price = close;

    klines.push({
      id: i + 1,
      symbol: '000001',
      time: new Date(Date.UTC(2026, 0, 1 + i, 9, 30)),
      open,
      high,
      low,
      close,
      volume: '10000',
      amount: '1000000',
    });
  }
  return klines;
}

describe('ChanVisualAdapter', () => {
  it('returns empty array when klines count is less than 3', () => {
    expect(ChanVisualAdapter.convert([])).toEqual([]);
    expect(ChanVisualAdapter.convert(generateSampleKlines(2))).toEqual([]);
  });

  it('converts sample K-lines into standard drawing commands (bi, duan, zhongshu, bsp)', () => {
    const klines = generateSampleKlines(60);
    const commands = ChanVisualAdapter.convert(klines);

    expect(commands.length).toBeGreaterThan(0);

    const biCommands = commands.filter((c) => c.layer === 'chan_bi');
    const zsBiCommands = commands.filter((c) => c.layer === 'chan_zs_bi');

    expect(biCommands.length).toBeGreaterThan(0);
    expect(biCommands[0]).toMatchObject({
      type: 'line',
      layer: 'chan_bi',
      color: '#FACC15',
    });

    if (zsBiCommands.length > 0) {
      expect(zsBiCommands[0]).toMatchObject({
        type: 'band',
        layer: 'chan_zs_bi',
        fill: true,
      });
    }
  });

  it('honors layer filtering options', () => {
    const klines = generateSampleKlines(60);
    const biOnly = ChanVisualAdapter.convert(klines, {
      includeBi: true,
      includeDuan: false,
      includeZhongshu: false,
      includeBsp: false,
    });

    expect(biOnly.every((c) => c.layer === 'chan_bi')).toBe(true);
  });

  it('renders confirmed-and-valid duan lines on real market cycles', () => {
    // 真实 5m 窗口（2026-06-29~07-03）：确认段渲染
    const klines = generateRealKlines();
    const commands = ChanVisualAdapter.convert(klines);
    const biCommands = commands.filter((c) => c.layer === 'chan_bi');
    const duanCommands = commands.filter((c) => c.layer === 'chan_duan');
    const zsDuanCommands = commands.filter((c) => c.layer === 'chan_zs_duan');

    expect(biCommands.length).toBeGreaterThan(0);
    expect(duanCommands.length).toBeGreaterThan(0); // 仅确认段渲染

    // 确认识别段中枢命令数量严格对齐 chancore 段中枢数量
    const { phaseB: bis } = ChanCore.createBi(klines);
    const duans = ChanCore.createDuan(bis);
    const duanChannels = ChanCore.createDuanChannels(duans);
    expect(zsDuanCommands.length).toBe(duanChannels.phaseB.length);

    // 数据完整性：确认段存在（防止数据退化后断言失去意义）
    expect(duans.some((d) => d.endBi !== null)).toBe(true);
    expect(duans.filter((d) => d.endBi !== null).length).toBe(
      duanCommands.length,
    );
  });

  it('does not render unconfirmed tail Duan (real-line fallback removed)', () => {
    // 合成 300 根窄幅锯齿只产生 UnComplete 尾段：按规则不画（历史实现靠
    // `endBi ?? originBis[last]` 兜底把它画成实线——此用例保护该兜底不复活）
    const klines = generateSampleKlines(300);
    const duans = ChanCore.createDuan(ChanCore.createBi(klines).phaseB);
    expect(duans.every((d) => d.endBi === null)).toBe(true); // 数据前提：全是未确认段

    const commands = ChanVisualAdapter.convert(klines);
    const duanCommands = commands.filter((c) => c.layer === 'chan_duan');
    expect(duanCommands.length).toBe(0);
  });

  it('renders centrals bounded by macroBis when provided', () => {
    const klines = generateRealKlines();
    const midIdx = Math.floor(klines.length / 2);
    const macroBi = {
      startTime: new Date(klines[0].time),
      endTime: new Date(klines[midIdx].time),
      low: 3900,
      high: 4200,
      trend: TrendDirection.Up,
      type: BiType.Complete,
      status: BiStatus.Valid,
      originIds: [klines[0].id, klines[midIdx].id],
      originData: [],
      independentCount: 2,
      startFenxing: null,
      endFenxing: null,
    };

    const commands = ChanVisualAdapter.convert(klines, {
      macroBis: [macroBi],
    });
    const zsCommands = commands.filter((c) => c.layer === 'chan_zs_bi');
    const macroEndMs = macroBi.endTime.getTime();
    for (const zs of zsCommands) {
      if (zs.type === 'band') {
        expect(new Date(zs.toTime).getTime()).toBeLessThanOrEqual(macroEndMs);
      }
    }
  });

  it('renders bi-centrals spanning from entry stroke end to exit stroke start', () => {
    const klines = generateRealKlines();
    const commands = ChanVisualAdapter.convert(klines);
    const zsCommands = commands.filter((c) => c.layer === 'chan_zs_bi');

    const { phaseB: channels } = ChanCore.createChannels(klines);
    if (channels.length > 0 && zsCommands.length > 0) {
      const firstZs = channels[0];
      const firstCmd = zsCommands[0] as any;
      // fromTime must equal bis[1].startTime (entry bi end), not bis[0].startTime
      expect(firstCmd.fromTime).toBe(
        new Date(firstZs.bis[1].startTime).toISOString(),
      );
      // toTime must equal bis[last].startTime (exit bi start), not bis[last].endTime
      expect(firstCmd.toTime).toBe(
        new Date(firstZs.bis[firstZs.bis.length - 1].startTime).toISOString(),
      );
    }
  });
});
